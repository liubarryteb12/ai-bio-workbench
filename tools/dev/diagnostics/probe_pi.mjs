
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import path from 'node:path';
const ROOT = 'D:/00.AIagent/codespace/AI辅助生信分析流程工作台';
const BD = path.join(ROOT, 'BioanalysDesktop');
const env = { ...process.env, BAD_PORT: '18994', BAD_AUTH_USER: 'probe', BAD_AUTH_PASS: 'probe-pass-123', SystemRoot: process.env.SystemRoot || 'C:\\Windows' };
const srv = spawn(process.execPath, ['server/index.js'], { cwd: BD, env, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 3500));
const browser = await chromium.launch();
const ctx = await browser.newContext({ httpCredentials: { username: 'probe', password: 'probe-pass-123' } });
const page = await ctx.newPage();
const calls = []; const errs = [];
page.on('response', async (res) => { if (res.url().includes('/api/pi-agent')) calls.push(res.status() + ' ' + res.url().split('/api/')[1]); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message.slice(0,200)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text().slice(0,200)); });
await page.goto('http://127.0.0.1:18994/', { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Pi Agent 监控' }).click();
await page.waitForTimeout(6000);
const text = (await page.locator('body').innerText()).replace(/\n{2,}/g, '\n').slice(0, 2500);
await page.screenshot({ path: path.join(ROOT, '.tmp', 'piagent_tab.png'), fullPage: false });
console.log('CALLS=' + JSON.stringify(calls));
console.log('ERRS=' + JSON.stringify(errs.slice(0,6)));
console.log('--- TEXT ---');
console.log(text);
await browser.close(); srv.kill();
