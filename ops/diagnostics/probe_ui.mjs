import { chromium } from 'playwright';
const PORT = process.env.PROBE_PORT || '18994';
const U = 'admin', P = process.env.PROBE_PASS;
const base = 'http://127.0.0.1:' + PORT;
const out = {};
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, httpCredentials: { username: U, password: P } });
const page = await ctx.newPage();
const errs = [];
page.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
page.on('pageerror', e => errs.push('PAGEERROR: ' + String(e).slice(0, 200)));
const reqs = [];
page.on('request', r => { const u = new URL(r.url()); if (u.pathname.startsWith('/api/')) reqs.push(u.pathname); });
await page.goto(base + '/', { waitUntil: 'networkidle', timeout: 30000 }).catch(e => errs.push('GOTO: ' + e.message.slice(0, 150)));
out.title = await page.title();
out.tabs = await page.$$eval('.tab-nav-item', els => els.map(e => e.textContent.trim()));
out.apiCalls = [...new Set(reqs)];
await page.screenshot({ path: '.tmp_ui_01_home.png', fullPage: false });
out.errors = errs.slice(0, 8);
console.log(JSON.stringify(out, null, 1));
await browser.close();
